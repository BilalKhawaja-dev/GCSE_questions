    @mock_aws
    @given(
        question_id=st.text(min_size=5, max_size=50, alphabet=st.characters(whitelist_categories=('Lu', 'Ll', 'Nd'))),
        topic=st.sampled_from(['fractions', 'algebra', 'geometry', 'statistics']),
        difficulty_score=st.integers(min_value=1, max_value=10),
        quality_score=st.floats(min_value=0.0, max_value=1.0)
    )
    @settings(max_examples=50, deadline=10000)
    def test_question_banking_storage(self, question_id, topic, difficulty_score, quality_score):
        """
        Feature: gcse-question-generator-v2, Property 9: Question Banking Storage
        For any refined question generated by RefinementLambda, it should be stored in the 
        Question_Bank S3 bucket with proper metadata.
        """
        # Setup mock S3
        s3 = boto3.client('s3', region_name='eu-west-2')
        bucket_name = 'test-question-bank-bucket'
        
        # Create the bucket
        s3.create_bucket(
            Bucket=bucket_name,
            CreateBucketConfiguration={'LocationConstraint': 'eu-west-2'}
        )
        
        # Arrange: Create improved question data
        improved_question = {
            'question_id': f"improved_{question_id}_{int(time.time())}",
            'question_text': f"Improved question about {topic}",
            'mark_scheme': {
                'marking_criteria': f"Marking criteria for {topic} question",
                'method_marks': 2,
                'accuracy_marks': 1
            },
            'metadata': {
                'topic': topic,
                'subtopic': f"{topic}_basics",
                'difficulty_score': difficulty_score,
                'tier': 'Foundation' if difficulty_score <= 5 else 'Higher',
                'assessment_objective': 'AO1',
                'learning_objective': f"Understand {topic} concepts"
            },
            'improvements_made': [
                "Clarified wording",
                "Adjusted difficulty level",
                "Added context"
            ],
            'refinement_metadata': {
                'original_question_id': question_id,
                'refinement_timestamp': int(time.time()),
                'original_quality_score': quality_score,
                'feedback_count': 10,
                'improvement_reasons': ['too_difficult', 'unclear_wording'],
                'bedrock_model': 'anthropic.claude-3-sonnet-20240229-v1:0'
            }
        }
        
        candidate = {
            'question_id': question_id,
            'quality_score': quality_score,
            'feedback_count': 10,
            'helpful_count': 3,
            'not_helpful_count': 7,
            'avg_difficulty_rating': float(difficulty_score),
            'last_updated': int(time.time())
        }
        
        # Mock environment variables
        with patch.dict('os.environ', {
            'QUESTION_BANK_BUCKET': bucket_name
        }):
            # Act: Store the improved question
            success = store_improved_question(question_id, improved_question, candidate)
            
            # Assert: Storage should succeed
            assert success is True, "Question banking storage should succeed"
            
            # Assert: Question should be stored in S3 with correct key
            expected_key = f"refined/improved/{improved_question['question_id']}.json"
            
            # Verify the object exists in S3
            try:
                response = s3.get_object(Bucket=bucket_name, Key=expected_key)
                stored_data = json.loads(response['Body'].read().decode('utf-8'))
                
                # Assert: Stored data should match improved question
                assert stored_data['question_id'] == improved_question['question_id']
                assert stored_data['question_text'] == improved_question['question_text']
                assert stored_data['metadata']['topic'] == topic
                assert stored_data['metadata']['difficulty_score'] == difficulty_score
                
                # Assert: Storage metadata should be added
                assert 'storage_metadata' in stored_data
                storage_metadata = stored_data['storage_metadata']
                assert storage_metadata['bucket'] == bucket_name
                assert storage_metadata['key'] == expected_key
                assert 'stored_at' in storage_metadata
                assert 'refinement_run_id' in storage_metadata
                
                # Assert: Refinement metadata should be preserved
                assert 'refinement_metadata' in stored_data
                refinement_metadata = stored_data['refinement_metadata']
                assert refinement_metadata['original_question_id'] == question_id
                assert refinement_metadata['original_quality_score'] == quality_score
                assert refinement_metadata['feedback_count'] == 10
                
                # Assert: Object metadata should be set correctly
                object_metadata = response.get('Metadata', {})
                assert object_metadata.get('original-question-id') == question_id
                assert object_metadata.get('quality-score') == str(quality_score)
                assert object_metadata.get('feedback-count') == '10'
                assert 'refinement-timestamp' in object_metadata
                
            except Exception as e:
                pytest.fail(f"Failed to retrieve stored question from S3: {str(e)}")

    @mock_aws
    @given(
        question_count=st.integers(min_value=1, max_value=5),
        topic=st.sampled_from(['fractions', 'algebra', 'geometry'])
    )
    @settings(max_examples=20, deadline=10000)
    def test_multiple_question_banking(self, question_count, topic):
        """
        Test that multiple refined questions are stored correctly with unique keys
        """
        # Setup mock S3
        s3 = boto3.client('s3', region_name='eu-west-2')
        bucket_name = 'test-question-bank-bucket'
        
        # Create the bucket
        s3.create_bucket(
            Bucket=bucket_name,
            CreateBucketConfiguration={'LocationConstraint': 'eu-west-2'}
        )
        
        stored_keys = []
        
        with patch.dict('os.environ', {
            'QUESTION_BANK_BUCKET': bucket_name
        }):
            # Store multiple questions
            for i in range(question_count):
                question_id = f"original_question_{i}_{uuid.uuid4().hex[:8]}"
                
                improved_question = {
                    'question_id': f"improved_{question_id}_{int(time.time())}_{i}",
                    'question_text': f"Improved question {i} about {topic}",
                    'mark_scheme': {
                        'marking_criteria': f"Marking criteria for question {i}",
                        'method_marks': 2,
                        'accuracy_marks': 1
                    },
                    'metadata': {
                        'topic': topic,
                        'difficulty_score': 5,
                        'tier': 'Foundation'
                    }
                }
                
                candidate = {
                    'question_id': question_id,
                    'quality_score': 0.5,
                    'feedback_count': 5
                }
                
                # Store the question
                success = store_improved_question(question_id, improved_question, candidate)
                assert success is True
                
                # Track the expected key
                expected_key = f"refined/improved/{improved_question['question_id']}.json"
                stored_keys.append(expected_key)
        
        # Verify all questions are stored with unique keys
        assert len(stored_keys) == question_count
        assert len(set(stored_keys)) == question_count, "All stored keys should be unique"
        
        # Verify all objects exist in S3
        for key in stored_keys:
            try:
                response = s3.get_object(Bucket=bucket_name, Key=key)
                stored_data = json.loads(response['Body'].read().decode('utf-8'))
                assert stored_data['metadata']['topic'] == topic
            except Exception as e:
                pytest.fail(f"Failed to retrieve question with key {key}: {str(e)}")

